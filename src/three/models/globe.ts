const X = (lon: number, w: number) => ((lon + 180) / 360) * w;
const Y = (lat: number, h: number) => ((90 - lat) / 180) * h;

function earthNight() {
  const w = 4096;
  const h = 2048;
  const c = document.createElement("canvas");
  c.width = w;
  c.height = h;
  const ctx = c.getContext("2d")!;
  const r = rng(77);
  const og = ctx.createLinearGradient(0, 0, 0, h);
  og.addColorStop(0, "#04101f");
  og.addColorStop(0.5, "#06172b");
  og.addColorStop(1, "#04101f");
  ctx.fillStyle = og;
  ctx.fillRect(0, 0, w, h);
  const path = new Path2D();
  for (const poly of LAND) {
    poly.forEach(([lo, la], i) => (i ? path.lineTo(X(lo, w), Y(la, h)) : path.moveTo(X(lo, w), Y(la, h))));
    path.closePath();
  }
  // land: dark olive-grey, a soft coastal glow
  ctx.save();
  ctx.shadowColor = "rgba(90,140,200,0.35)";
  ctx.shadowBlur = 18;
  ctx.fillStyle = "#16201f";
  ctx.fill(path);
  ctx.restore();
  ctx.save();
  ctx.clip(path);
  for (let k = 0; k < 2200; k++) {
    ctx.fillStyle = `rgba(${40 + r() * 30},${50 + r() * 30},${40 + r() * 20},${0.15 + r() * 0.2})`;
    ctx.beginPath();
    ctx.arc(r() * w, r() * h, 6 + r() * 40, 0, Math.PI * 2);
    ctx.fill();
  }
  // city lights: a warm core with scattered suburbs, only on land
  for (const [lo, la, s] of CITIES) {
    const cx = X(lo, w);
    const cy = Y(la, h);
    const g = ctx.createRadialGradient(cx, cy, 0, cx, cy, 34 * s);
    g.addColorStop(0, "rgba(255,214,140,0.95)");
    g.addColorStop(0.3, "rgba(255,170,80,0.35)");
    g.addColorStop(1, "rgba(255,150,60,0)");
    ctx.fillStyle = g;
    ctx.fillRect(cx - 40 * s, cy - 40 * s, 80 * s, 80 * s);
    for (let k = 0; k < 160 * s; k++) {
      const a = r() * Math.PI * 2;
      const d = Math.pow(r(), 1.6) * 70 * s;
      ctx.fillStyle = `rgba(255,${190 + r() * 50},${110 + r() * 60},${0.25 + r() * 0.55})`;
      ctx.fillRect(cx + Math.cos(a) * d, cy + Math.sin(a) * d * 0.8, 1.6, 1.6);
    }
  }
  // faint lights along coasts and in dense plains
  for (let k = 0; k < 9000; k++) {
    const x = r() * w;
    const y = h * (0.15 + r() * 0.55);
    if (!ctx.isPointInPath(path, x, y)) continue;
    ctx.fillStyle = `rgba(255,200,120,${0.06 + r() * 0.2})`;
    ctx.fillRect(x, y, 1.4, 1.4);
  }
  ctx.restore();
  const t = new THREE.CanvasTexture(c);
  t.colorSpace = THREE.SRGBColorSpace;
  t.anisotropy = 8;
  return t;
}

export function lonLat(lon: number, lat: number, radius: number, out = new THREE.Vector3()) {
  const phi = ((90 - lat) * Math.PI) / 180;
  const th = ((lon + 180) * Math.PI) / 180;
  return out.set(-radius * Math.sin(phi) * Math.cos(th), radius * Math.cos(phi), radius * Math.sin(phi) * Math.sin(th));
}

export function buildGlobe(radius = 1) {
  const g = new THREE.Group();
  const map = earthNight();
  const earth = new THREE.Mesh(
    new THREE.SphereGeometry(radius, 128, 64),
    new THREE.MeshStandardMaterial({ map, emissiveMap: map, emissive: new THREE.Color("#ffffff"), emissiveIntensity: 0.85, roughness: 0.8, metalness: 0 }),
  );
  g.add(earth);
  // atmosphere: a fresnel rim on a slightly larger back-faced sphere
  const atmo = new THREE.Mesh(
    new THREE.SphereGeometry(radius * 1.045, 96, 48),
    new THREE.ShaderMaterial({
      transparent: true,
      side: THREE.BackSide,
      depthWrite: false,
      blending: THREE.AdditiveBlending,
      uniforms: { c: { value: new THREE.Color("#5aa0ff") } },
      vertexShader: "varying vec3 vN; varying vec3 vV; void main(){ vec4 mv = modelViewMatrix*vec4(position,1.0); vN = normalize(normalMatrix*normal); vV = normalize(-mv.xyz); gl_Position = projectionMatrix*mv; }",
      fragmentShader: "uniform vec3 c; varying vec3 vN; varying vec3 vV; void main(){ float f = pow(1.0 - abs(dot(vN, vV)), 2.2); gl_FragColor = vec4(c, f*0.9); }",
    }),
  );
  g.add(atmo);
  return { group: g, earth };
}
